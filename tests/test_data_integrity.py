def test_synthetic_vcf_gate(tmp_path):
    """Falsification: a broken counter (records lost, genotypes miscounted,
    Ti/Tv misassigned, filters dropped), a 'chr'-prefix regression in the
    fixture generator, or missing PGT/PID wiring would turn this red. The
    exact counts below are derived from the construction rules in
    _wgs_like_variants, not from the code under test."""
    vcf = tmp_path / "standin_wgs.vcf"
    synth.write_vcf(vcf, _wgs_like_variants(2000), contigs=STANDIN_CONTIGS)

    stats, head, sex = _assert_vcf_gate(
        vcf, n_bounds=(1000, 3000), titv_bounds=(1.8, 2.2),
        expected_filters=set(FILTERS_USED))

    # Totals consistent with what was written (2000 records, 500/contig).
    assert stats["n_records"] == 2000
    assert stats["n_snv"] == 1846          # 2000 - 154 indels (i%13==0)
    assert stats["n_indel"] == 154
    assert stats["n_with_rsid"] == 100     # i%20==0
    assert stats["n_multiallelic"] == 0
    assert stats["genotypes"]["het"] == 1800
    assert stats["genotypes"]["hom_alt"] == 200
    assert stats["genotypes"]["hom_ref"] == 0
    assert stats["n_phased_gt"] == 1800    # every het carries PGT
    assert stats["filter_histogram"]["PASS"] == 1979
    for f in FILTERS_USED:
        assert stats["filter_histogram"][f] == 7   # 21 non-PASS / 3 names
    for c in _CHROMS:
        assert stats["per_contig"][c]["n_records"] == 500

    # Qual sanity from the planted distribution 50..98 in 0.5 steps.
    assert stats["qual"]["min"] == 50.0
    assert stats["qual"]["max"] == 98.0
    assert stats["qual"]["median"] is not None
    assert 50.0 <= stats["qual"]["median"] <= 98.0
    assert stats["qual"]["mean"] is not None

    # All 500 chrX records are het in this fixture -> female-like signal;
    # no chrY contig -> zero Y calls.
    assert sex["inferred"] == "female"
    assert sex["x_het_rate"] == 1.0
    assert sex["n_y_calls"] == 0


def test_sex_check_explicit_counts():
    """Falsification: threshold or denominator errors flip the planted
    male/female patterns; missing chrX must yield 'ambiguous', not a guess."""
    male = sex_check({"X": {"het": 4, "hom_alt": 600, "haploid": 400},
                      "Y": {"het": 0, "hom_alt": 120}})
    assert male["inferred"] == "male"
    assert male["n_y_calls"] == 120
    female = sex_check({"X": {"het": 500, "hom_alt": 200, "hom_ref": 100}})
    assert female["inferred"] == "female"
    assert female["x_het_rate"] == pytest.approx(500 / 800)
    assert sex_check({"1": {"het": 10, "hom_alt": 5}})["inferred"] \
        == "ambiguous"                      # no chrX at all
    mid = sex_check({"X": {"het": 80, "hom_alt": 600, "hom_ref": 120}})
    assert mid["inferred"] == "ambiguous"   # het rate 0.1 between bounds


def test_docx_hpo_extraction(tmp_path):
    """Falsification: HPO-regex drift or docx/XML mishandling drops or
    mangles HP codes; the CLI's guards must fire on a term-free docx and on
    a missing file, not silently emit an empty hpo_terms.json. Also covers
    an 8-digit typo code: an unanchored regex would truncate it to a
    plausible-looking but WRONG 7-digit code instead of excluding it."""
    codes = ["HP:0001234", "HP:0002350", "HP:0011001"]
    docx = synth.write_docx(tmp_path / "pheno.docx", [
        "Clinical summary: proband shows growth delay HP:0001234 .",
        "Additional findings: HP:0002350 and recurrent HP:0011001 noted.",
        "This paragraph carries no codes.",
        "HP:0001234 again (duplicate must dedupe in document order).",
        "Typo code HP:00099999 must not be truncated into a fake match.",
    ])
    terms = extract_hpo_from_docx(docx)
    assert terms == codes
    # the truncated-prefix contamination the unanchored regex would produce
    assert "HP:0009999" not in terms

    # End-to-end through the CLI entry point.
    out = tmp_path / "hpo_terms.json"
    assert hpo_cli.main(["--docx", str(docx), "--out", str(out)]) == 0
    payload = json.loads(out.read_text())
    assert payload == {"proband_id": "PROBAND01", "hpo_terms": codes,
                       "source": "pheno.docx"}

    # Guards: term-free docx and missing file both exit nonzero.
    empty = synth.write_docx(tmp_path / "empty.docx",
                             ["no ontology codes anywhere"])
    assert hpo_cli.main(["--docx", str(empty),
                         "--out", str(tmp_path / "x.json")]) != 0
    assert hpo_cli.main(["--docx", str(tmp_path / "missing.docx"),
                         "--out", str(tmp_path / "y.json")]) != 0


def _fastp_fixture(total_reads=808_000_000, q30=0.935, gc=0.41, dup=0.084,
                   bases=121_200_000_000):
    """Minimal fastp-shaped report (structure verified vs fastp schema)."""
    return {
        "summary": {
            "before_filtering": {
                "total_reads": total_reads,
                "total_bases": bases,
                "q20_bases": int(bases * 0.97),
                "q30_bases": int(bases * q30),
                "q30_rate": q30,
                "read1_mean_length": 150,
                "read2_mean_length": 150,
                "gc_content": gc,
            },
            "after_filtering": {
                "total_reads": int(total_reads * 0.99),
                "total_bases": int(bases * 0.99),
                "q30_rate": q30 + 0.001,
                "gc_content": gc,
            },
        },
        "duplication": {"rate": dup},
    }


def test_fastp_compare_flags_outlier(tmp_path):
    """Falsification: tolerance math applied to the wrong side (+-20%
    around the measured value instead of the expectation, or percent-vs-
    fraction unit confusion) either fails to flag the planted GC outlier or
    wrongly flags an in-range metric."""
    good_p = tmp_path / "fastp_good.json"
    bad_p = tmp_path / "fastp_bad.json"
    good_p.write_text(json.dumps(_fastp_fixture()))
    bad_p.write_text(json.dumps(_fastp_fixture(gc=0.60)))  # planted anomaly

    stats = parse_fastp_json(bad_p)
    assert stats["total_reads"] == 808_000_000
    assert stats["read_pairs"] == 404_000_000   # mates halved
    cmp_bad = compare_to_expectations(stats)
    assert cmp_bad["checks"]["gc_content"]["status"] == "fail"
    assert cmp_bad["checks"]["read_pairs"]["status"] == "pass"
    assert cmp_bad["checks"]["q30_rate"]["status"] == "pass"
    assert cmp_bad["checks"]["duplication_rate"]["status"] == "pass"
    assert cmp_bad["checks"]["coverage_x"]["status"] == "pass"  # ~39x in tol
    assert cmp_bad["all_pass"] is False

    cmp_good = compare_to_expectations(parse_fastp_json(good_p))
    assert cmp_good["all_pass"] is True
    assert cmp_good["n_measured"] == 5


def test_parse_fastq_stats_fallback(tmp_path):
    """Falsification: a phred+33 off-by-one, a GC denominator that includes
    Ns, or broken .gz handling moves the planted fractions; duplication must
    be reported 'missing' (unmeasurable from a raw stream), never faked."""
    reads = [("ATGTACGTAC", "??????????"),   # all Q>=30, GC 0.4
             ("AAAAAAAAAA", "5555555555"),   # all Q20, GC 0.0
             ("GGGGGGGGGG", "IIIIIIIIII"),   # all Q40, GC 1.0
             ("NNNNNNNNNN", "5555555555")]   # Q20; Ns excluded from GC denom
    text = "".join(f"@r{i}\n{s}\n+\n{q}\n"
                   for i, (s, q) in enumerate(reads))
    p = tmp_path / "t.fastq.gz"
    with gzip.open(p, "wt") as fh:
        fh.write(text)

    st = parse_fastq_stats(p)
    assert st["n_reads"] == 4
    assert st["total_bases"] == 40
    assert st["mean_read_len"] == 10.0
    # GC denom = 30 ACGT bases (the 10 Ns excluded): gc = 4+0+10 -> ~0.467
    assert st["gc_fraction"] == pytest.approx(14 / 30)
    # Q30: '?'=='I' qualify (20 of 40 qual chars) -> 0.5
    assert st["q30_fraction"] == 0.5

    cmp = compare_to_expectations(st)
    assert cmp["checks"]["duplication_rate"]["status"] == "missing"
    assert cmp["checks"]["q30_rate"]["status"] == "fail"   # .5 vs .935
    assert cmp["checks"]["gc_content"]["status"] == "pass"  # .467 within tol


def test_run_fastqc_cli_exit_code_reflects_all_pass(tmp_path):
    """Falsification: GATE 1 requires read counts within 20% of expectation
    to be a red/green criterion. main() unconditionally returning 0 would
    let a real contamination/read-count anomaly stay invisible to
    ``make gate``/CI, discoverable only by a human opening the summary."""
    fq_dir = tmp_path / "fastq"
    fq_dir.mkdir()
    (fq_dir / "fastp.json").write_text(json.dumps(_fastp_fixture(gc=0.60)))
    out_bad = tmp_path / "out_bad"
    assert run_fastqc_cli.main(["--fastq-dir", str(fq_dir),
                               "--out", str(out_bad)]) != 0

    fq_dir_good = tmp_path / "fastq_good"
    fq_dir_good.mkdir()
    (fq_dir_good / "fastp.json").write_text(json.dumps(_fastp_fixture()))
    out_good = tmp_path / "out_good"
    assert run_fastqc_cli.main(["--fastq-dir", str(fq_dir_good),
                               "--out", str(out_good)]) == 0


def test_run_eda_cli(tmp_path):
    """Falsification: nondeterminism (timestamps, dict-order drift) or a
    missing output file breaks the regenerated-tables rule (plan.md Phase
    6 - no hand-typed stats in the report)."""
    vcf = tmp_path / "standin.vcf"
    synth.write_vcf(vcf, _wgs_like_variants(2000), contigs=STANDIN_CONTIGS)
    out = tmp_path / "eda"
    assert run_eda_cli.main(["--vcf", str(vcf), "--out", str(out)]) == 0
    j = out / "eda_report.json"
    m = out / "eda_summary.md"
    assert j.exists() and m.exists()
    first_bytes = j.read_bytes()
    assert run_eda_cli.main(["--vcf", str(vcf), "--out", str(out)]) == 0
    assert j.read_bytes() == first_bytes      # byte-identical rerun
    rep = json.loads(j.read_text())
    assert rep["stats"]["n_records"] == 2000
    assert rep["header"]["chr_prefix"]["none"] is True
    assert rep["sex_check"]["inferred"] == "female"
    assert "Ti/Tv" in m.read_text()


def test_real_vcf_gate():
    """GATE-1 harness on the patient VCF, unchanged (plan.md Phase 1): the
    same battery as the synthetic run with WGS expectation bounds - variant
    count in [3M, 7M], Ti/Tv in [1.9, 2.1]. Any red assertion = stop and
    explain the anomaly in docs/decisions.md before Phase 2. Skips until
    MVA_REAL_VCF points at the downloaded file."""
    path = os.environ.get("MVA_REAL_VCF")
    if not path or not Path(path).exists():
        pytest.skip("MVA_REAL_VCF not set - point it at the patient WGS "
                    "VCF (e.g. data/WGS_EX2312012_HGWCNDSX7.vcf.gz)")
    stats, head, sex = _assert_vcf_gate(
        path, n_bounds=(3_000_000, 7_000_000), titv_bounds=(1.9, 2.1))
    rep = integrity_report(path)
    json.dumps(rep)                          # JSON-able end to end
    assert rep["stats"] == stats
    assert rep["header"] == head
    assert stats["n_with_rsid"] > 0
    # The inferred value itself is recorded, not asserted - an expectation
    # about the patient is not evidence; disagreement is reported honestly.
    assert sex["inferred"] in {"male", "female", "ambiguous"}
