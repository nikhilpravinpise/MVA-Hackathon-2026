# Stand-in contig set: bare names, same convention as the challenge VCF.
STANDIN_CONTIGS = {c: synth.CONTIGS[c] for c in ("1", "7", "15", "X")}
_CHROMS = list(STANDIN_CONTIGS)  # ["1", "7", "15", "X"]

# Non-PASS FILTER tokens emitted into the fixture (i % 97 == 0 records,
# name chosen by i % 3 so all three appear exactly 7 times each).
FILTERS_USED = ("LowQual", "VQSRTrancheSNP99.90to100.00", "ReadPosRankSumLow")

_TI = {"A": "G", "G": "A", "C": "T", "T": "C"}          # transition partner
_TV = {"A": "C", "G": "T", "C": "A", "T": "G"}          # one fixed transversion
_REFS = "ACGT"


def _wgs_like_variants(n: int = 2000) -> list[SVar]:
    """Deterministic ~WGS-shaped variant list (no RNG - byte-stable fixture).

    Construction rules:
      * contigs cycle 1/7/15/X; positions step 50 kb per contig;
      * every 13th record is a 1-bp insertion (indel);
      * remaining SNVs emit a transition ~2/3 of the time and a
        transversion ~1/3 -> Ti/Tv lands at ~2.0 inside [1.8, 2.2];
      * GT = "1/1" every 10th record (hom-alt), else "0/1" with PGT/PID
        set (hets exercise the phasing fields);
      * FILTER non-PASS every 97th record, cycling FILTERS_USED;
      * dbSNP-style rs ID every 20th record.
    """
    out: list[SVar] = []
    pos = {c: 1_000_000 for c in _CHROMS}
    for i in range(n):
        chrom = _CHROMS[i % 4]
        ref = _REFS[i % 4]
        if i % 13 == 0:
            alt = ref + _REFS[(i + 1) % 4]      # insertion -> indel
        elif i % 3 == 0:
            alt = _TV[ref]                       # transversion (~1/3)
        else:
            alt = _TI[ref]                       # transition (~2/3)
        gt = "1/1" if i % 10 == 0 else "0/1"
        filt = FILTERS_USED[i % 3] if i % 97 == 0 else None
        out.append(SVar(
            chrom, pos[chrom], ref, alt,
            vid=f"rs{1_000_000 + i}" if i % 20 == 0 else ".",
            qual=50.0 + (i % 97) * 0.5,
            filters=(filt,) if filt else ("PASS",),
            gt=gt,
            pgt=("1|0" if i % 2 == 0 else "0|1") if gt == "0/1" else None,
            pid="PS_STANDIN" if gt == "0/1" else None,
        ))
        pos[chrom] += 50_000
    return out


def _assert_vcf_gate(vcf_path, n_bounds, titv_bounds, expected_filters=None):
    """The shared Gate-1 assertion battery over ``vcf_path``.

    Same checks for the synthetic stand-in and the patient VCF; only the
    expectation bounds differ. Returns (stats, header, sex) so callers can
    add fixture-specific assertions.
    """
    stats = compute_stats(vcf_path)
    head = header_forensics(vcf_path)

    # 1) Contigs: bare names, NO 'chr' prefix anywhere (the silent tabix
    #    trap - queries written in 'chr*' style would return nothing).
    assert head["contigs"], "no contigs declared in VCF header"
    assert head["chr_prefix"]["none"], (
        "expected bare contigs; 'chr'-prefixed names found: "
        f"{[c['name'] for c in head['contigs'] if c['chr_prefix']]}")
    for c in head["contigs"]:
        assert not c["name"].startswith("chr"), c["name"]

    # 2) PGT/PID FORMAT fields present (Sentieon physical-phasing inputs
    #    that src/phasing.py and Gate 3 depend on).
    assert head["format_fields"]["PGT"], "PGT missing from FORMAT defs"
    assert head["format_fields"]["PID"], "PID missing from FORMAT defs"

    # 2b) When CSQ is present, at least one gnomAD AF field name must match
    #     what src.triage's rarity gate actually reads (gnomADe*_AF /
    #     gnomADg*_AF) - a differently-named AF plugin field would silently
    #     score every variant as absent-from-gnomAD with no error raised.
    if head["csq"]["present"] and head["csq"]["n_fields"] > 0:
        assert head["csq"]["gnomad_af_fields"], (
            "CSQ present but no gnomADe*_AF/gnomADg*_AF field name found "
            f"among {head['csq']['fields']} - src/triage.py's gnomAD "
            "absence bonus would silently misfire on every variant")

    # 3) Variant count: >0 and inside the stated bounds.
    assert stats["n_records"] > 0
    assert n_bounds[0] <= stats["n_records"] <= n_bounds[1], (
        f"n_records={stats['n_records']} outside {n_bounds}")

    # 4) Ti/Tv inside the stated window (generator target on the stand-in;
    #    ~2.0 WGS expectation on the patient file).
    assert stats["titv"] is not None, "no transversions observed at all"
    assert titv_bounds[0] <= stats["titv"] <= titv_bounds[1], (
        f"titv={stats['titv']} outside {titv_bounds}")

    # 5) Every FILTER value enumerated in the histogram; PASS accounted.
    hist = stats["filter_histogram"]
    assert hist, "filter histogram empty"
    assert hist.get("PASS", 0) == stats["n_pass"]
    nonpass = set(hist) - {"PASS"}
    assert all(isinstance(f, str) and f for f in nonpass)
    if expected_filters is not None:
        assert nonpass == set(expected_filters), (
            f"observed non-PASS filters {sorted(nonpass)} != "
            f"expected {sorted(expected_filters)}")

    # 6) Internal consistency of the stat bundle + JSON serializability.
    assert stats["n_snv"] + stats["n_indel"] == stats["n_records"]
    assert stats["n_pass"] + stats["n_filtered"] == stats["n_records"]
    assert sum(stats["genotypes"].values()) == stats["n_records"]
    assert (sum(c["n_records"] for c in stats["per_contig"].values())
            == stats["n_records"])
    json.dumps({"stats": stats, "header": head})

    sex = sex_check(stats)
    assert sex["inferred"] in {"male", "female", "ambiguous"}
    return stats, head, sex


