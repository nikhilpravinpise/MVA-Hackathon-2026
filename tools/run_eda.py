"""CLI: VCF EDA report writer (plan.md Phase 1 - "judge the data before
trusting it").

    python tools/run_eda.py --vcf data/<patient>.vcf.gz --out results/eda
    python tools/run_eda.py --vcf results/spike_case/spike_proband.vcf \
        --out results/eda_spike

Writes ``eda_report.json`` (the full ``src.vcf_qc.integrity_report`` bundle)
and ``eda_summary.md`` (human-readable tables of the same numbers - no
hand-typed stats, per the Phase 6 reproducibility rule) into ``--out``.

Deterministic: identical inputs give byte-identical outputs (no timestamps,
sorted JSON keys, fixed table order). Runs on the synthetic stand-in today
and on the patient VCF unchanged once it lands (plan.md sec.7).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from src.vcf_qc import integrity_report  # noqa: E402


def _fmt(v, nd: int = 4) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render_summary(report: dict) -> str:
    """Markdown summary of an integrity_report dict. Deterministic."""
    s = report["stats"]
    h = report["header"]
    x = report["sex_check"]
    L: list[str] = []
    L.append("# VCF EDA summary")
    L.append("")
    L.append(f"Source VCF: `{s['vcf']}` - sample: `{s['sample']}` "
             "(all numbers regenerated by tools/run_eda.py; no hand-edited "
             "stats).")
    L.append("")
    L.append("## Headline stats")
    L.append("")
    L.append(_table(
        ["metric", "value"],
        [
            ["records", s["n_records"]],
            ["SNV", s["n_snv"]],
            ["indel/other", s["n_indel"]],
            ["multiallelic", s["n_multiallelic"]],
            ["with dbSNP/rs ID", s["n_with_rsid"]],
            ["PASS", s["n_pass"]],
            ["filtered", s["n_filtered"]],
            ["transitions", s["transitions"]],
            ["transversions", s["transversions"]],
            ["Ti/Tv", _fmt(s["titv"])],
            ["phased genotypes (| or PGT)", s["n_phased_gt"]],
        ]))
    L.append("")
    L.append("## QUAL distribution")
    L.append("")
    q = s["qual"]
    L.append(_table(
        ["n", "missing", "min", "median", "mean", "max"],
        [[q["n"], q["n_missing"], _fmt(q["min"], 2), _fmt(q["median"], 2),
          _fmt(q["mean"], 2), _fmt(q["max"], 2)]]))
    L.append("")
    L.append("## Genotypes (sample column)")
    L.append("")
    g = s["genotypes"]
    L.append(_table(
        ["bucket", "count"],
        [[k, g[k]] for k in
         ("het", "hom_alt", "hom_ref", "haploid", "no_call")]))
    L.append("")
    L.append("## FILTER histogram (every observed FILTER token)")
    L.append("")
    L.append(_table(
        ["filter", "records"],
        [[k, v] for k, v in s["filter_histogram"].items()]))
    L.append("")
    L.append("## Per-contig counts")
    L.append("")
    L.append(_table(
        ["contig", "records", "pass", "filtered", "het", "hom_alt",
         "hom_ref", "haploid", "no_call"],
        [[c] + [d[k] for k in ("n_records", "n_pass", "n_filtered", "het",
                               "hom_alt", "hom_ref", "haploid", "no_call")]
         for c, d in s["per_contig"].items()]))
    L.append("")
    L.append("## Header forensics")
    L.append("")
    cp = h["chr_prefix"]
    L.append(_table(
        ["check", "result"],
        [
            ["fileformat", h["fileformat"] or "absent"],
            ["contigs declared", len(h["contigs"])],
            ["chr prefix any/all/none",
             f"{cp['any']}/{cp['all']}/{cp['none']}"],
            ["FORMAT PGT present", h["format_fields"]["PGT"]],
            ["FORMAT PID present", h["format_fields"]["PID"]],
            ["FORMAT ids", ", ".join(h["format_ids"]) or "none"],
            ["INFO CSQ present", h["csq"]["present"]],
            ["CSQ fields parsed", h["csq"]["n_fields"]],
            ["FILTER ids declared",
             ", ".join(h["filter_ids"]) or "none declared"],
            ["reference meta", h["reference"] or "absent"],
            ["source meta", "; ".join(h["source"]) or "absent"],
            ["caller-like meta lines",
             "; ".join(h["caller_lines"]) or "none"],
            ["INFO AF definition", h["af_info_definition"] or "absent"],
            ["INFO AF interpretation", h["af_interpretation"]],
            ["samples", ", ".join(h["samples"]) or "none"],
        ]))
    L.append("")
    L.append("## Sex-consistency check (chrX het rate + chrY calls)")
    L.append("")
    L.append(_table(
        ["signal", "value"],
        [
            ["inferred", x["inferred"]],
            ["chrX het rate", _fmt(x["x_het_rate"])],
            ["chrX het / called", f"{x['x_het']}/{x['x_called']}"],
            ["chrY called", x["n_y_calls"]],
            ["notes", "; ".join(x["notes"]) or "none"],
        ]))
    L.append("")
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="VCF EDA / integrity report (plan.md Phase 1)")
    ap.add_argument("--vcf", required=True, help="input VCF (plain or .gz)")
    ap.add_argument("--out", required=True,
                    help="output dir for eda_report.json + eda_summary.md")
    ap.add_argument("--sample", default=None,
                    help="sample name for genotype stats (default: first)")
    args = ap.parse_args(argv)

    if not Path(args.vcf).exists():
        print(f"ERROR: VCF not found: {args.vcf}", file=sys.stderr)
        return 2

    report = integrity_report(args.vcf, sample=args.sample)

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "eda_report.json").write_text(
        json.dumps(report, indent=1, sort_keys=True) + "\n",
        encoding="utf-8")
    (out_dir / "eda_summary.md").write_text(
        render_summary(report), encoding="utf-8", newline="")

    s = report["stats"]
    print(f"records={s['n_records']} snv={s['n_snv']} indel={s['n_indel']} "
          f"titv={_fmt(s['titv'])} pass={s['n_pass']} "
          f"sex={report['sex_check']['inferred']}")
    print(f"wrote {out_dir / 'eda_report.json'} and "
          f"{out_dir / 'eda_summary.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
