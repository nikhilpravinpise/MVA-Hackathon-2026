"""Emit the bwa-mem2 re-alignment + locus-validation pipeline (plan.md Phase 3).

    python tools/run_realign.py --ref env/ref/GRCh38_no_alt.fa \
        --fastq-dir data/fastq --work-dir work/align \
        --vcf data/WGS.vcf.gz --region 1:1000000-1100000 --dry-run

    python tools/run_realign.py ... --write-script tools/ext/realign.sh

Steps emitted (all tool paths are parameterized - see flags):

  1. bwa-mem2 index <ref.fa>                      (one-time, ~3 GB GRCh38)
  2. per-lane bwa-mem2 mem -t N -R <RG> ref R1 R2 | samtools sort -> lane.bam
     (4 lanes x R1/R2 pairs, ~404M pairs total - deep dive 9b)
  3. samtools merge lane BAMs -> merged.bam; samtools markdup -> dedup.bam
  4. mosdepth coverage (genome-wide + per-window) on dedup.bam
  5. samtools view -b dedup.bam REGION > region.bam  (locus export for IGV)
  6. whatshap phase --reference ref.fa VCF region.bam -> phased region VCF
     (independent phase call to check against PGT/PID)
  7. deepvariant run_deepvariant --model_type WGS --regions REGION on
     dedup.bam -> independent caller concordance vs the shipped Sentieon VCF

CONTIG-NAME CONTRACT (deep dive section 2, load-bearing)
--------------------------------------------------------
The reference MUST be the GRCh38 *no-alt analysis set* whose contigs carry NO
'chr' prefix (1, 2, ... X, M) - the same convention as the challenge VCF.
Closest public file: GIAB/NCBI
`GCA_000001405.15_GRCh38_no_alt_analysis_set_maskedGRC_exclusions_v2.fasta.gz`.
Region strings here are therefore `15:<start>-<end>` style - never
`chr15:...` (a chr-prefixed region against a no-chr BAM silently returns
empty). The reference the shipped VCF used additionally names
`plus_hs38d1` and `no_chr` in its header; MD5 was never published, so record
our file's sha256 when it is fetched.

`--region` has NO default: the locus is decided by the pipeline's own ranked
output, not by any public/leaked coordinate list (firewall, plan.md 2.1.5).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LANES = ["L001", "L002", "L003", "L004"]


def build_script(args) -> str:
    ref = args.ref
    fq = args.fastq_dir.rstrip("/\\")
    work = args.work_dir.rstrip("/\\")
    sample = args.sample
    region = args.region
    lanes = args.lanes.split(",") if args.lanes else LANES
    bwa, sam, mos = args.bwa, args.samtools, args.mosdepth
    wh, dv = args.whatshap, args.deepvariant_image
    t = args.threads

    lane_align = "\n".join(
        f"{bwa} mem -t {t} "
        f"-R '@RG\\tID:{ln}\\tSM:{sample}\\tPL:ILLUMINA\\tPU:{ln}' "
        f"$REF {fq}/{args.fastq_template.format(lane=ln, read='R1')} "
        f"{fq}/{args.fastq_template.format(lane=ln, read='R2')} | \\\n"
        f"    {sam} sort -@4 -o $WORK/lane_{ln}.bam -"
        for ln in lanes)
    lane_bams = " ".join(f"$WORK/lane_{ln}.bam" for ln in lanes)

    return f"""#!/usr/bin/env bash
# Generated by tools/run_realign.py - bwa-mem2 realignment + locus validation.
# Reference contigs must be NO-CHR (bare '15'), matching the challenge VCF.
# Run under WSL2 / Linux container; log wall-time to docs/runtime_log.md.
set -euo pipefail

REF="{ref}"          # GRCh38 no-alt, NO chr prefix
WORK="{work}"
SAMPLE="{sample}"
REGION="{region}"    # bare-contig form e.g. 1:1000000-1100000

# --- 1. one-time index (~30-60 min, ~3 GB ref) ---
{bwa} index "$REF"

# --- 2. per-lane align -> sorted BAM (~404M pairs total) ---
{lane_align}

# --- 3. merge + duplicate-mark + index ---
{sam} merge -@8 -o $WORK/merged.bam {lane_bams}
{sam} markdup -@8 $WORK/merged.bam $WORK/{sample}.dedup.bam
{sam} index $WORK/{sample}.dedup.bam
{sam} flagstat $WORK/{sample}.dedup.bam > $WORK/flagstat.txt

# --- 4. coverage (expect ~35x mean; flag locus-level confounders) ---
{mos} -t 8 -n --by 500 $WORK/mosdepth $WORK/{sample}.dedup.bam
{mos} -t 8 -n $WORK/mosdepth_region $WORK/{sample}.dedup.bam $REGION

# --- 5. locus BAM export (read-level evidence figure) ---
{sam} view -b $WORK/{sample}.dedup.bam $REGION > $WORK/region.bam
{sam} index $WORK/region.bam
{sam} view $WORK/{sample}.dedup.bam $REGION | head  # sanity: non-empty

# --- 6. whatshap phase on region BAM + shipped VCF (2nd phase opinion) ---
{wh} phase -o $WORK/phased.vcf --reference=$REF {args.vcf} $WORK/region.bam

# --- 7. DeepVariant --regions: independent recall + GT concordance ---
docker run --rm -v "$WORK":/work -v "$(dirname "$REF")":/refdir \\
    {dv} /opt/deepvariant/bin/run_deepvariant \\
        --model_type WGS --ref /refdir/$(basename "$REF") \\
        --reads /work/{sample}.dedup.bam \\
        --output_vcf /work/dv_region.vcf.gz \\
        --output_gvcf /work/dv_region.g.vcf.gz \\
        --regions "$REGION" --num_shards {t}
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="bwa-mem2 realign pipeline emitter")
    ap.add_argument("--ref", required=True, help="GRCh38 no-alt fasta (no-chr contigs)")
    ap.add_argument("--fastq-dir", required=True)
    ap.add_argument("--fastq-template",
                    default="WGS_EX2312012_HGWCNDSX7_S16_{lane}_{read}_001.fastq.gz",
                    help="filename template with {lane} and {read} slots")
    ap.add_argument("--work-dir", default="work/align")
    ap.add_argument("--vcf", required=True, help="shipped VCF for whatshap input")
    ap.add_argument("--region", required=True,
                    help="bare-contig locus, e.g. 1:1000000-1100000 "
                         "(from pipeline output - no default by design)")
    ap.add_argument("--sample", default="PROBAND01")
    ap.add_argument("--lanes", default=",".join(LANES))
    ap.add_argument("--threads", type=int, default=16)
    ap.add_argument("--bwa", default="bwa-mem2")
    ap.add_argument("--samtools", default="samtools")
    ap.add_argument("--mosdepth", default="mosdepth")
    ap.add_argument("--whatshap", default="whatshap")
    ap.add_argument("--deepvariant-image", default="google/deepvariant:1.10.0")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the script only")
    ap.add_argument("--write-script", default=None, metavar="PATH",
                    help="also write a runnable bash script to PATH")
    args = ap.parse_args(argv)

    if args.region.lower().startswith("chr"):
        print("WARNING: --region looks chr-prefixed; the reference BAM uses "
              "bare contigs - 'chr15:...' returns empty (deep dive sec.2)",
              file=sys.stderr)

    script = build_script(args)
    print(script)
    if args.write_script:
        p = Path(args.write_script)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(script, encoding="utf-8", newline="\n")
        print(f"\n[written] {p} (chmod +x on the linux side)", file=sys.stderr)
    if not args.dry_run and not args.write_script:
        print("\n[hint] re-run with --write-script PATH to save, or --dry-run "
              "to preview only", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
